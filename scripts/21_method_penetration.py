"""ML / CV study: where have the rising methods arrived? Share of each task / application domain's papers that use each method.

For the question "how to choose a topic" (user, 2026-10-15): a method that is rising overall but rare inside a domain
is either an open gap or a poor fit; this table cannot tell which, it only shows where the methods are and are not yet.
Measure: final title + abstract matrix (data/topic_matrix_ta.csv), raw shares (no venue standardisation: domains are
subsets of papers), full years 2021, 2023 and 2025 (2026 is incomplete). Lift = share inside the domain / share in all
papers of the same year (1 = the method is as common in the domain as in all six venues).
Output: results/method_penetration.csv (long), results/method_penetration.md (2025 matrices)
"""
import os

import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
METHODS = ["Diffusion models / score-based", "Flow matching / normalizing flows", "Transformers / attention",
           "State-space models / Mamba / linear attention", "LLMs / language models", "Vision-language / multimodal LLMs",
           "Foundation models", "Reasoning / chain-of-thought", "Fine-tuning / PEFT / prompting", "Reinforcement learning",
           "Self-supervised / contrastive learning", "Knowledge distillation", "3D Gaussian splatting", "Neural fields / NeRF"]
DOMAINS = ["Image classification / recognition", "Object detection", "Segmentation", "Tracking / re-identification",
           "Human pose / body / hands", "Object 6D pose estimation", "Face analysis", "Image restoration / low-level vision",
           "Video understanding / action recognition", "Visual QA / captioning / grounding", "OCR / documents / charts",
           "Image retrieval / metric learning", "Medical imaging", "Remote sensing / earth observation", "Autonomous driving",
           "Event cameras / computational imaging", "3D reconstruction / SfM / SLAM", "Depth / stereo / optical flow / matching",
           "Novel view synthesis / neural rendering", "Point clouds / 3D understanding", "Image generation / editing",
           "Video generation / editing", "3D / 4D generation", "3D humans / avatars / motion",
           "AI for science: molecules / proteins / materials", "Scientific ML / PDEs / physics", "Time series / forecasting",
           "Speech / audio / music", "NLP tasks", "Robotics / embodied AI", "Healthcare / clinical", "Tabular data",
           "Combinatorial optimization / scheduling", "Recommendation / information retrieval", "Graph learning / knowledge graphs"]
SHORT = {"Diffusion models / score-based": "Diffusion", "Flow matching / normalizing flows": "Flows", "Transformers / attention": "Transformer",
         "State-space models / Mamba / linear attention": "SSM/Mamba", "LLMs / language models": "LLM",
         "Vision-language / multimodal LLMs": "VLM/MLLM", "Foundation models": "Foundation", "Reasoning / chain-of-thought": "Reasoning",
         "Fine-tuning / PEFT / prompting": "Fine-tune/PEFT", "Reinforcement learning": "RL", "Self-supervised / contrastive learning": "Self-sup.",
         "Knowledge distillation": "Distill.", "3D Gaussian splatting": "3DGS", "Neural fields / NeRF": "NeRF"}
YEARS = [2021, 2023, 2025]


def main():
    m = pd.read_csv(os.path.join(ROOT, "data", "topic_matrix_ta.csv"))
    rows = []
    for y in YEARS:
        g = m[m.year == y]
        for d in DOMAINS + ["(all papers)"]:
            sub = g if d == "(all papers)" else g[g[d] == 1]
            for meth in METHODS:
                k, n = int(sub[meth].sum()), len(sub)
                overall = g[meth].mean()
                rows.append({"year": y, "domain": d, "method": meth, "k": k, "n": n, "pct": 100 * k / n if n else 0.0,
                             "lift": (k / n) / overall if n and overall else float("nan")})
    out = pd.DataFrame(rows)
    out.to_csv(os.path.join(ROOT, "results", "method_penetration.csv"), index=False)
    L = ["# Where the rising methods have arrived (ML / CV) (title + abstract, raw shares)", "",
         "Generated by scripts/21_method_penetration.py. Cell = % of the domain's 2025 papers that use the method (papers);",
         "the second table divides by the method's share in all 2025 papers (lift; 1 = as common as in all six venues).",
         "A low value means the method is rare in that domain: an open gap or a poor fit; the table cannot tell which.", ""]
    y = 2025
    t = out[out.year == y]
    n_dom = t.groupby("domain").n.first()
    head = "| domain (2025 papers) | " + " | ".join(SHORT[x] for x in METHODS) + " |"
    sep = "|---|" + "---|" * len(METHODS)
    def table(val):
        lines = [head, sep]
        for d in ["(all papers)"] + DOMAINS:
            r = t[t.domain == d].set_index("method")
            lines.append(f"| {d} ({n_dom[d]:,}) | " + " | ".join(val(r.loc[x]) for x in METHODS) + " |")
        return lines
    L += ["## Share of the domain's 2025 papers that use the method, % (papers)", ""]
    L += table(lambda r: f"{r.pct:.1f} ({r.k})")
    L += ["", "## Lift in 2025 (domain share / overall share)", ""]
    L += table(lambda r: "–" if pd.isna(r.lift) else f"{r.lift:.2f}")
    L += ["", "## Change of the share inside the domain, 2021 → 2023 → 2025 (%)", ""]
    lines = [head, sep]
    for d in ["(all papers)"] + DOMAINS:
        cells = []
        for x in METHODS:
            v = [out[(out.year == yy) & (out.domain == d) & (out.method == x)].pct.iloc[0] for yy in YEARS]
            cells.append(" → ".join(f"{a:.1f}" for a in v))
        lines.append(f"| {d} | " + " | ".join(cells) + " |")
    L += lines + [""]
    with open(os.path.join(ROOT, "results", "method_penetration.md"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote results/method_penetration.csv, results/method_penetration.md")
    # Relative attention: papers name more topics each year (abstracts longer, more combinations), so every share drifts up.
    # Baseline = growth of all topic mentions (sum of the standardised shares); a topic whose share grows less than the
    # baseline is losing ground relative to the rest, even when its own trend is "rising".
    sc = pd.read_csv(os.path.join(ROOT, "results", "shares_and_change_ta.csv"))
    first, ref = 2020, 2025
    base = sc[f"share_{ref}"].sum() / sc[f"share_{first}"].sum()
    ra = sc[["topic", "family", f"share_{first}", f"share_{ref}", "call"]].copy()
    ra["ratio"] = ra[f"share_{ref}"] / ra[f"share_{first}"]
    ra["ratio_vs_baseline"] = ra["ratio"] / base
    ra = ra.sort_values("ratio_vs_baseline", ascending=False)
    ra.to_csv(os.path.join(ROOT, "results", "relative_attention.csv"), index=False)
    mean_k = m.assign(k=m[[c for c in sc.topic]].sum(axis=1)).groupby("year").k.mean()
    with open(os.path.join(ROOT, "results", "relative_attention.md"), "w") as f:
        f.write(f"# Relative attention {first} -> {ref} (generated by scripts/21_method_penetration.py)\n\n")
        f.write("Topics named per paper: " + ", ".join(f"{y} {v:.2f}" for y, v in mean_k.items()) + ".\n")
        f.write(f"All topic mentions grew x{base:.3f} from {first} to {ref} (sum of standardised shares). ratio = share {ref} / "
                f"share {first}; ratio_vs_baseline < 1 = the topic grew slower than mentions overall.\n\n")
        f.write(ra.round(3).to_markdown(index=False) + "\n")
    print(f"baseline x{base:.3f}; wrote results/relative_attention.csv/.md")


if __name__ == "__main__":
    main()
