"""results/REPORT.md — main report on the title + abstract measure (generated from results/shares_and_change_ta.csv)."""
import os

import pandas as pd
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import config  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
d = pd.read_csv(os.path.join(ROOT, "results", "shares_and_change_ta.csv")).sort_values(f"share_{config.REF_YEAR}", ascending=False)
papers = pd.read_csv(os.path.join(ROOT, "data", "topic_matrix_ta.csv"))
cov = papers.groupby(["venue", "year"]).size().unstack(fill_value=0).reindex(config.VENUES)
arrow = {"rising": "↑ rising", "declining": "↓ declining", "unclear": "· unclear"}


Y = config.YEARS
import json  # noqa: E402
_ab = pd.DataFrame([json.loads(l) for l in open(os.path.join(ROOT, "data", "abstracts.jsonl"))])
ABS_WORDS = _ab.assign(w=_ab.abstract.str.split().str.len()).groupby("year").w.median().to_dict()


def line(r):
    shares = " | ".join(f"{getattr(r, f'share_{y}'):.1f}%" for y in Y)
    rec = {"rising": " ↑", "declining": " ↓", "unclear": ""}[r.recent_call]
    return (f"| {r.topic} | {shares} | {r.change_pp:+.1f} | ×{r.annual_OR:.2f} [{r.annual_OR_lo:.2f}, {r.annual_OR_hi:.2f}] "
            f"| ×{r.recent_OR:.2f}{rec} | {arrow[r.call]} |")


L = [f"# ML / CV topics at top conferences, {Y[0]}–{Y[-1]}: share and change (title + abstract)", "",
     "Generated by scripts/15_report.py from results/shares_and_change_ta.csv.", "",
     "**Measure.** A paper counts for a topic if the topic's rule matches its title or its abstract (rules: scripts/04_topics.py;",
     "abstract-specific rules for generic words; precision checks: results/precision_review.md).",
     "**Papers** = main-track papers of NeurIPS, ICML, ICLR, CVPR, ICCV and ECCV (dblp, plus ICML 2026 from PMLR; workshops,",
     "co-located events, Tiny Papers, position papers and competition / demo tracks excluded: scripts/03_build_dataset.py).",
     "**Share** = percentage of papers, standardised to the venue mix of 2024 + 2025 (both ICCV and ECCV are in it) so that",
     "the years compare; a venue that did not meet in a year (ICCV in even years, ECCV in odd years, NeurIPS 2026 not yet",
     "held) contributes its model-estimated share (95% intervals in results/shares_and_change_ta.csv).",
     "**Change** = first to last year in percentage points;",
     "**per year** = annual odds multiplier over the whole period from topic ~ venue + year (95% CI), **recent** = the same",
     "over 2024–2026 (↑/↓ when significant); **trend** uses the whole period, Benjamini–Hochberg q < 0.05.", "",
     f"Papers with abstracts ({len(papers):,}):", "", cov.to_markdown(), "",
     "## All topics, by 2025 share", "",
     "| topic | " + " | ".join(str(y) for y in Y[:-1]) + f" | {Y[-1]} (est.) | change {Y[0]}→{str(Y[-1])[2:]} (points) | per year {Y[0]}–{str(Y[-1])[2:]} | recent 24–26 | trend |",
     "|---|" + "---|" * (len(Y) + 4),
     *[line(r) for r in d.itertuples()], "",
     "## Number of papers per topic and year", "",
     f"Raw counts, all six venues (the shares above are standardised; these are not). Counts jump between years because ICCV",
     f"and ECCV alternate and the venues grew; {Y[-1]} has ICLR, ICML, CVPR and ECCV (NeurIPS {Y[-1]} meets in December;",
     f"ICML {Y[-1]} comes from PMLR, the dblp dump did not have it yet), so {Y[-1]} counts are not comparable with earlier years.", "",
     "| topic | " + " | ".join(str(y) for y in Y[:-1]) + f" | {Y[-1]} (part) | all years |", "|---|" + "---|" * (len(Y) + 1),
     "| **all papers** | " + " | ".join(f"**{(papers.year == y).sum():,}**" for y in Y) + f" | **{len(papers):,}** |",
     *[f"| {r.topic} | " + " | ".join(f"{int(getattr(r, f'n_{y}')):,}" for y in Y) + f" | {sum(int(getattr(r, f'n_{y}')) for y in Y):,} |"
       for r in d.itertuples()], "",
     "## Reading notes", "",
     "- Shares overlap: a paper can count for several topics (e.g. a multimodal-LLM paper is usually also an LLM paper).",
     "- A share counts papers that use the topic's words in the topic's sense, including passing mentions; it is not a count of papers whose main contribution is the topic.",
     "- NeurIPS is the largest venue (" + f"{int(cov.loc['NeurIPS'].max()):,}" + " papers in its largest year); the venues more than tripled in size from 2020 to 2025.",
     "- Reasoning is counted in abstracts by capability phrasing (mathematical/visual/spatial reasoning, reasoning ability, chain of thought, test-time compute).",
     "- Abstracts got longer: median " + ", ".join(f"{y}: {int(w)}" for y, w in ABS_WORDS.items()) + " words. Counting any mention,",
     "  a longer abstract has more chances to name a topic, so part of a small rise can come from length alone; length does not",
     "  explain the large risers.", ""]
# per-venue section (scripts/20_scope_trends.py)
st = pd.read_csv(os.path.join(ROOT, "results", "scope_trends_ta.csv"))
sig = st[(st.call != "unclear") & (st.scope != "All venues")].copy()
def seq(r):
    ys = [int(y) for y in r.years.split(",")]
    return " → ".join(f"{r[f'share_{y}']:.1f}% ({int(r[f'k_{y}'])}/{int(r[f'n_{y}'])})" for y in ys)
L += ["## By venue", "",
      "Same measure per scope: each venue alone (raw shares, Wilson intervals in results/scope_trends_ta.csv), and the",
      "ML and Vision groups (standardised to the group's 2024 + 2025 venue mix). Trend = likelihood-ratio test of the year",
      "term; Benjamini–Hochberg within each scope. ICCV and ECCV each have only three or four years.", "",
      "Significant trends by scope (outside the all-venue table):", "",
      "| scope | topic | share per year (papers) | q | trend |", "|---|---|---|---|---|",
      *[f"| {r['scope']} | {r['topic']} | {seq(r)} | {r['q']:.3g} | {arrow[r['call']]} |" for _, r in sig.sort_values(["scope", "q"]).iterrows()],
      "", "Topic × venue matrix of the latest-year share: results/venue_matrix_ta.md.", ""]
with open(os.path.join(ROOT, "results", "REPORT.md"), "w") as f:
    f.write("\n".join(L) + "\n")
print("wrote results/REPORT.md")
